/**
 * Build-time step: compiles Electron main-process modules to V8 bytecode
 * (.jsc) with bytenode, so the packaged app.asar no longer contains readable
 * JavaScript source for the main process (including config.cjs and
 * env.generated.cjs, which hold the embedded API config).
 *
 * Output goes to electron-obf/, mirroring electron/:
 *   - each module ships as <name>.jsc (bytecode) + a tiny <name>.cjs stub
 *     that loads it via bytenode
 *   - preload.cjs is copied as plain source: the renderer preload runs in a
 *     sandboxed context that cannot require('bytenode')
 *
 * The packaged build uses electron-obf/main.cjs as its entry point (see
 * build.extraMetadata.main in package.json); dev keeps using electron/.
 *
 * IMPORTANT: bytecode must be generated by the same V8 + OS/arch that runs it,
 * so this compiles through the project's Electron binary (bytenode's
 * `electron: true` mode, which runs it with ELECTRON_RUN_AS_NODE). This step
 * therefore runs on the machine that builds the installers (mac/win), as part
 * of `npm run dist*` — it cannot run on Replit.
 *
 * Cross-platform note: Mac-built .jsc files crash on Windows with
 * `cachedDataRejected`. Use `--plain` (or `--for-win` when not on win32) to
 * ship readable main-process JS for Windows installers built from macOS.
 *
 * NOTE: bytecode is strong obfuscation, not true secrecy — a determined
 * attacker with enough effort can still analyze it. Real security must be
 * enforced server-side.
 */
const path = require('node:path');
const fs = require('node:fs');
const bytenode = require('bytenode');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'electron');
const OUT = path.join(ROOT, 'electron-obf');

// Compile everything except the sandboxed preload (which cannot load
// bytenode) — that ships as plain source; it contains no secrets.
const COMPILE = [
  'main.cjs',
  'config.cjs',
  'env.generated.cjs',
  'httpsOnly.cjs',
  'errorMonitor.cjs',
  'tokenVault.cjs',
  'auth.cjs',
  'certPin.cjs',
  'location.cjs',
  'sosMonitor.cjs',
  'pushService.cjs',
  'panelWindows.cjs',
  'deepLink.cjs',
  'ctx.cjs',
  'recordingProtocol.cjs',
  'siteBrowserView.cjs',
  'autoUpdateSetup.cjs',
  'ipcRegistry.cjs',
  'siteAuth.cjs',
  'fcmToken.cjs',
  'fcmListener.cjs',
  'secure/index.cjs',
  'secure/registry.cjs',
  'secure/crypto.cjs',
  'secure/bridgeSanitize.cjs',
  'secure/devHttpLog.cjs',
];
const COPY_PLAIN = [
  'preload.cjs',
  'sitePreload.cjs',
  'sosAlertPreload.cjs',
  'sos-alert.html',
  'assets/danger.webm',
];

// `--node` compiles with the local Node.js instead of Electron. Only for
// smoke-testing the pipeline (e.g. on Replit); NEVER use it for real builds —
// Node's V8 differs from Electron's and the app would crash at startup.
const useNode = process.argv.includes('--node');
// `--plain` / `--for-win` on non-Windows: copy sources (no .jsc) so a
// Windows installer built from macOS does not ship incompatible bytecode.
const forWin = process.argv.includes('--for-win');
const usePlain =
  process.argv.includes('--plain') || (forWin && process.platform !== 'win32');

function copyModule(rel) {
  const src = path.join(SRC, rel);
  const dest = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

async function main() {
  if (!fs.existsSync(path.join(SRC, 'env.generated.cjs'))) {
    console.error(
      'compile-bytecode: electron/env.generated.cjs missing. Run `npm run embed:env` first.',
    );
    process.exit(1);
  }

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, 'secure'), { recursive: true });

  if (usePlain) {
    for (const rel of COMPILE) {
      const src = path.join(SRC, rel);
      if (!fs.existsSync(src)) {
        console.error(`compile-bytecode: missing source file electron/${rel}`);
        process.exit(1);
      }
      copyModule(rel);
    }
    for (const rel of COPY_PLAIN) {
      copyModule(rel);
    }
    console.log(
      `compile-bytecode: copied ${COMPILE.length} plain modules to electron-obf/ (cross-platform / --plain)`,
    );
    return;
  }

  for (const rel of COMPILE) {
    const src = path.join(SRC, rel);
    if (!fs.existsSync(src)) {
      console.error(`compile-bytecode: missing source file electron/${rel}`);
      process.exit(1);
    }
    const jsc = path.join(OUT, rel.replace(/\.cjs$/, '.jsc'));
    await bytenode.compileFile({
      filename: src,
      output: jsc,
      electron: !useNode,
      compileAsModule: true,
    });

    // Loader stub with the original filename so relative require()s between
    // modules keep working unchanged.
    const jscBase = path.basename(jsc);
    const stub =
      rel === 'main.cjs'
        ? `'use strict';\nrequire('bytenode');\nrequire('./${jscBase}');\n`
        : `'use strict';\nrequire('bytenode');\nmodule.exports = require('./${jscBase}');\n`;
    fs.writeFileSync(path.join(OUT, rel), stub);
  }

  for (const rel of COPY_PLAIN) {
    fs.copyFileSync(path.join(SRC, rel), path.join(OUT, rel));
  }

  const mode = useNode ? 'node (SMOKE TEST ONLY)' : 'electron';
  console.log(
    `compile-bytecode: wrote ${COMPILE.length} .jsc modules + stubs to electron-obf/ (target: ${mode})`,
  );
}

main().catch((err) => {
  console.error('compile-bytecode failed:', err);
  process.exit(1);
});
