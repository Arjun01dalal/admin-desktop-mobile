/**
 * Build-time step: embeds required env values into the packaged app so the
 * plaintext `.env` file no longer ships in the installer's Resources folder.
 *
 * Hardening: values are XOR-encrypted with a random per-build key, split into
 * shuffled fragments, and reassembled at runtime. Nothing greppable like the
 * URL or key appears as a contiguous string in the shipped files.
 *
 * NOTE: this is strong obfuscation, not true secrecy — code running on a
 * user's machine can always be reverse-engineered by a determined attacker.
 * Real security must be enforced server-side.
 */
const path = require('node:path');
const fs = require('node:fs');
const crypto = require('node:crypto');
const dotenv = require('dotenv');

const ROOT = path.join(__dirname, '..');
const ENV_PATH = path.join(ROOT, '.env');
const OUT_PATH = path.join(ROOT, 'electron', 'env.generated.cjs');

const REQUIRED = ['API_BASE_URL', 'ENTK_VALUE'];
const OPTIONAL = [
  'MOBILE_CDN_BASE',
  'GH_UPDATE_TOKEN',
  'SOS_PUSH_TOPIC',
  'SOS_PUSH_SERVER',
  'RECORDING_BASIC_AUTH_USERNAME',
  'RECORDING_BASIC_AUTH_PASSWORD',
];

if (!fs.existsSync(ENV_PATH)) {
  console.error('generate-embedded-env: .env not found. Copy .env.example to .env and fill it in.');
  process.exit(1);
}

const parsed = dotenv.parse(fs.readFileSync(ENV_PATH));
const missing = REQUIRED.filter((k) => !parsed[k]);
if (missing.length) {
  console.error(`generate-embedded-env: missing required keys in .env: ${missing.join(', ')}`);
  process.exit(1);
}

const FRAGMENT_LEN = 6;

function obfuscate(value, key) {
  const buf = Buffer.from(value, 'utf8');
  const out = Buffer.alloc(buf.length);
  for (let i = 0; i < buf.length; i++) out[i] = buf[i] ^ key[i % key.length];

  // Split ciphertext into fragments and shuffle their storage order.
  const fragments = [];
  for (let i = 0; i < out.length; i += FRAGMENT_LEN) {
    fragments.push(out.subarray(i, i + FRAGMENT_LEN).toString('hex'));
  }
  const order = fragments.map((_, i) => i);
  for (let i = order.length - 1; i > 0; i--) {
    const j = crypto.randomInt(i + 1);
    [order[i], order[j]] = [order[j], order[i]];
  }
  const shuffled = order.map((idx) => fragments[idx]);
  return { f: shuffled, o: order };
}

const key = crypto.randomBytes(32);
const names = [...REQUIRED, ...OPTIONAL].filter((k) => parsed[k]);
// Obscure even the variable names.
const nameMap = names.map((n) => Buffer.from(n, 'utf8').toString('hex'));
const data = names.map((n) => obfuscate(parsed[n], key));

const out = `// AUTO-GENERATED by scripts/generate-embedded-env.cjs — do not edit or commit.
'use strict';
const K = Buffer.from(${JSON.stringify(key.toString('hex'))}, 'hex');
const N = ${JSON.stringify(nameMap)};
const D = ${JSON.stringify(data)};

function reassemble({ f, o }) {
  const ordered = new Array(f.length);
  o.forEach((originalIndex, storedIndex) => {
    ordered[originalIndex] = f[storedIndex];
  });
  const cipher = Buffer.from(ordered.join(''), 'hex');
  const plain = Buffer.alloc(cipher.length);
  for (let i = 0; i < cipher.length; i++) plain[i] = cipher[i] ^ K[i % K.length];
  return plain.toString('utf8');
}

module.exports = Object.fromEntries(
  N.map((hexName, i) => [Buffer.from(hexName, 'hex').toString('utf8'), reassemble(D[i])]),
);
`;

fs.writeFileSync(OUT_PATH, out);
console.log(`generate-embedded-env: wrote ${path.relative(ROOT, OUT_PATH)} (${names.length} values, XOR+fragmented)`);
