/**
 * Build-time step: embeds required env values into the packaged app so the
 * plaintext `.env` file no longer ships in the installer's Resources folder.
 *
 * Reads `.env` and writes `electron/env.generated.cjs` (gitignored) with the
 * values base64-encoded. NOTE: this is obfuscation, not encryption — any
 * client-side value can be extracted by a determined attacker. Real security
 * must be enforced server-side.
 */
const path = require('node:path');
const fs = require('node:fs');
const dotenv = require('dotenv');

const ROOT = path.join(__dirname, '..');
const ENV_PATH = path.join(ROOT, '.env');
const OUT_PATH = path.join(ROOT, 'electron', 'env.generated.cjs');

const REQUIRED = ['API_BASE_URL', 'ENTK_VALUE'];
const OPTIONAL = ['MOBILE_CDN_BASE'];

if (!fs.existsSync(ENV_PATH)) {
  console.error('generate-embedded-env: .env not found. Copy .env.example to .env and fill it in.');
  process.exit(1);
}

const parsed = dotenv.parse(fs.readFileSync(ENV_PATH));
const missing = REQUIRED.filter((k) => !parsed[k]);
if (missing.length) {
  console.error(`generate-embedded-env: missing required keys in .env: ${missing.join(', ')}`);
  process.exit(1);
}

const entries = [...REQUIRED, ...OPTIONAL]
  .filter((k) => parsed[k])
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(Buffer.from(parsed[k], 'utf8').toString('base64'))},`)
  .join('\n');

const out = `// AUTO-GENERATED by scripts/generate-embedded-env.cjs — do not edit or commit.
const encoded = {
${entries}
};

module.exports = Object.fromEntries(
  Object.entries(encoded).map(([k, v]) => [k, Buffer.from(v, 'base64').toString('utf8')]),
);
`;

fs.writeFileSync(OUT_PATH, out);
console.log(`generate-embedded-env: wrote ${path.relative(ROOT, OUT_PATH)}`);
